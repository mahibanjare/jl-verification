/**
 * Generates the importable Google Sheet database (.xlsx) with every tab
 * and header the backend expects (same schema as setup() in Code.gs).
 *
 * Usage:  node scripts/gen-database.cjs
 *
 * Tip: importing is optional — running setup() in Apps Script on a blank
 * sheet creates the same tabs AND formats columns as text (recommended).
 * If you import this file, still run setup() once afterwards.
 */
const fs = require('fs');
const path = require('path');
const XLSX = require('xlsx');

const cfg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'src', 'app.config.json'), 'utf8'));

const JSON_COLS = ['Visit', 'Residence', 'Employment', 'Business', 'Bank', 'ITR', 'Other Docs', 'Photos', 'Comments'];
const SCHEMA = {
  Login: ['Timestamp', 'Serial No', 'Full Name', 'Contact No', 'Email', 'Designation', 'User ID', 'Password', 'Role', 'Active', 'Telegram Chat ID'],
  Cases: [
    'Timestamp', 'Case No', 'Client', 'Branch', 'Product', 'Activity', 'Applicant Name', 'Applicant Mobile',
    'Applicant Address', 'Business Name', 'Occupation', 'Verifications Required', 'Assigned To', 'Executive Name',
    'Status', 'Allocated At', 'Started At', 'Submitted At', 'Reported At', 'Sent At', 'Reviewer Note',
    'Report Version', 'Photo Count', 'Updated At', 'Updated By', ...JSON_COLS,
  ],
  Reports: ['Timestamp', 'Case No', 'Version', 'Generated By', 'File Name'],
  Audit: ['Timestamp', 'Case No', 'User ID', 'Action', 'Details'],
  Settings: ['Key', 'Value'],
};
// Master tabs come from app.config.json.
(cfg.modules || []).forEach((m) => {
  SCHEMA[m.sheet] = ['Timestamp', ...(m.autoId ? [m.idColumn] : []), ...m.fields.map((f) => f.key)];
});

const wb = XLSX.utils.book_new();
Object.entries(SCHEMA).forEach(([name, headers]) => {
  const rows = [headers];
  // Default admin (plaintext here; hashed automatically on first login).
  if (name === 'Login') rows.push(['', 1, 'Administrator', '', '', 'Admin', 'admin', 'admin123', 'ADMIN', 'Yes', '']);
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows), name);
});

const outName = 'JL-Verify-Database.xlsx';
XLSX.writeFile(wb, path.join(__dirname, '..', outName));
console.log('Created ' + outName + ' with tabs: ' + wb.SheetNames.join(', '));
